use ramjetd::apps::js_num_str;
#[test] fn matches_ecmascript_number_to_string() {
                                                                                                             
    let cases: &[(f64, &str)] = &[
        (0.0, "0"), (-0.0, "0"), (1.0, "1"), (-5.0, "-5"), (0.5, "0.5"), (123456789012345.0, "123456789012345"),
        (1e15, "1000000000000000"), (1e20, "100000000000000000000"), (1e21, "1e+21"), (1.5e22, "1.5e+22"), (1e22, "1e+22"),
        (-1e21, "-1e+21"), (1.7976931348623157e308, "1.7976931348623157e+308"), (0.000001, "0.000001"), (1e-7, "1e-7"),
        (1.5e-7, "1.5e-7"), (-2.5e-10, "-2.5e-10"), (5e-324, "5e-324"), (9007199254740992.0, "9007199254740992"),
        (0.1 + 0.2, "0.30000000000000004"), (f64::INFINITY, "Infinity"), (f64::NEG_INFINITY, "-Infinity"), (f64::NAN, "NaN"),
        (123.456, "123.456"), (100.0, "100"), (999999999999999900000.0, "999999999999999900000"),
    ];
    for (n, want) in cases { assert_eq!(js_num_str(*n), *want, "{n:?}"); }
}
