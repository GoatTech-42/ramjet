import { chromium } from "playwright";
const [,, token, w, h, prefix] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: +w, height: +h } });
await ctx.addCookies([{ name: "rj2_session", value: token, url: "http://127.0.0.1:14224" }]);
const page = await ctx.newPage();
await page.goto("http://127.0.0.1:14224/jetstream", { waitUntil: "networkidle" });
await page.fill(".bar input", "lofi girl");
await page.click(".bar button");
await page.waitForSelector(".row img", { timeout: 15000 });
await page.waitForTimeout(1000);
await page.screenshot({ path: `qa/shots/${prefix}-results.png` });
await page.click(".row");
await page.waitForSelector(".frame video", { timeout: 20000 });
await page.waitForTimeout(5000);
const t = await page.evaluate(() => document.querySelector(".frame video")?.currentTime ?? -1);
await page.screenshot({ path: `qa/shots/${prefix}-watch.png` });
console.log("PLAYHEAD_SECONDS", t.toFixed(1));
await browser.close();
